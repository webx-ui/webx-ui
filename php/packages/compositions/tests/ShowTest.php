<?php

declare(strict_types=1);

namespace WebxUi\Compositions\Tests;

use Illuminate\Support\Facades\Artisan;
use PHPUnit\Framework\Attributes\Test;

/** `webx:composition:show` (COMPOSITIONS §8): the final tree, and who made it so. */
final class ShowTest extends TestCase
{
    #[Test]
    public function without_a_composition_it_lists_the_compositions_their_handles_and_files(): void
    {
        $this->artisan('webx:composition:show')
            ->expectsOutputToContain('layout.minimal extends layout')
            ->expectsOutputToContain('handles: default, blog.article')
            ->expectsOutputToContain('module-a/resources/compositions/layout/default.json')
            ->assertSuccessful();
    }

    #[Test]
    public function the_tree_says_who_added_moved_changed_and_removed_each_node(): void
    {
        $this->theme('layout', 'default', [
            'attrs' => ['html' => ['data-webx-smooth-scroll' => true]],
            'move' => [['id' => 'footer', 'to' => 'body', 'first' => true]],
        ]);
        $this->theme('layout', 'blog.article', [
            'add' => [['id' => 'reading-progress', 'to' => 'body', 'after' => 'header', 'html' => '<div></div>']],
            'remove' => ['a.note'],
        ]);

        Artisan::call('webx:composition:show', ['composition' => 'layout', '--handle' => 'blog.article', '--origin' => true]);
        $output = Artisan::output();

        $this->assertStringContainsString('layout × blog.article', $output);
        $this->assertMatchesRegularExpression('/^html\s+<html data-webx-smooth-scroll>\s+fixture\/theme; attrs\.data-webx-smooth-scroll ← .*layout\/default\.json$/m', $output);
        $this->assertMatchesRegularExpression('/^    footer\s+view components\.footer\s+fixture\/theme; move ← /m', $output);
        $this->assertMatchesRegularExpression('/^    reading-progress\s+html\s+\S*webx-compositions-theme-\S+$/m', $output);
        $this->assertMatchesRegularExpression('/^removed: a\.note ← .*layout\/blog\.article\.json$/m', $output);
    }

    #[Test]
    public function json_carries_the_tree_with_the_origin_of_every_node(): void
    {
        $this->theme('layout', 'default', ['remove' => ['footer', 'nothing']]);

        Artisan::call('webx:composition:show', ['composition' => 'layout', '--json' => true]);
        $data = json_decode(Artisan::output(), true);

        $this->assertSame('layout', $data['composition']);
        $this->assertSame('html', $data['tree']['id']);
        $this->assertSame('fixture/theme', $data['tree']['origin']);
        $this->assertSame([['id' => 'footer', 'file' => $this->local.'/compositions/layout/default.json']], $data['removed']);
        $this->assertSame('remove nothing', $data['findings'][0]['operation']);

        $main = $this->child($this->child($data['tree'], 'body'), 'main');
        $note = $this->child($main, 'a.note');
        $this->assertSame('module-a', $note['origin']);
        $this->assertFalse($note['base']);
    }

    #[Test]
    public function blade_prints_what_the_compiler_writes(): void
    {
        Artisan::call('webx:composition:show', ['composition' => 'layout.minimal', '--blade' => true]);

        $this->assertStringStartsWith('{{-- Generated by webx-ui/compositions: layout.minimal × default', Artisan::output());
        $this->assertStringNotContainsString('footer', Artisan::output());
    }

    #[Test]
    public function an_unknown_composition_or_a_broken_file_fails(): void
    {
        $this->artisan('webx:composition:show', ['composition' => 'nope'])
            ->expectsOutputToContain('No layer has a base for the composition "nope"')
            ->assertFailed();

        $this->theme('layout', 'default', '{ not json');

        $this->artisan('webx:composition:show')->expectsOutputToContain('invalid JSON')->assertFailed();
        $this->artisan('webx:composition:show', ['composition' => 'layout'])->assertFailed();
    }

    /**
     * @param  array<string, mixed>  $node
     * @return array<string, mixed>
     */
    private function child(array $node, string $id): array
    {
        foreach ($node['children'] ?? [] as $child) {
            if ($child['id'] === $id) {
                return $child;
            }
        }

        $this->fail("no child \"{$id}\" in \"{$node['id']}\"");
    }
}
