<?php

declare(strict_types=1);

namespace WebxUi\Compositions;

/**
 * A tree as the Blade view it stands for (COMPOSITIONS §2.3, §6.1): a line a node, four spaces a
 * level — the children of <html> on its own, the way documents are written —, components by
 * static tags, values as literals. The HTML comes out as a hand-written view with the same nodes
 * would print it, so a layout without patches prints the page it printed before it was a tree.
 */
final class Emitter
{
    private const string INDENT = '    ';

    /** Elements without a closing tag or content. */
    private const array VOID = ['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'];

    public function __construct(private readonly Probe $probe) {}

    /** The whole tree, with a comment saying where it comes from. */
    public function view(Tree $tree, string $composition, string $handle): string
    {
        $lines = $this->node($tree->root, '', $tree);
        $from = implode(', ', $tree->layers);

        return "{{-- Generated by webx-ui/compositions: {$composition} × {$handle}, from {$from}. Do not edit: change compositions/{$composition}/*.json. --}}\n"
            .implode("\n", $lines)."\n";
    }

    /**
     * The children of one container, for `<x-webx-composition::place>` (§6.4): all of them, or
     * only what was added above the base. Slots are the caller's: a hand-written view prints its
     * own `{{ $slot }}`.
     */
    public function children(Tree $tree, Node $container, bool $added): string
    {
        $lines = [];

        foreach ($container->children as $child) {
            if ($child->kind === 'slot' || ($added && $child->base)) {
                continue;
            }

            array_push($lines, ...$this->node($child, '', $tree));
        }

        return $lines === [] ? '' : implode("\n", $lines)."\n";
    }

    /** @return list<string> */
    private function node(Node $node, string $indent, Tree $tree): array
    {
        return match ($node->kind) {
            'tag' => $this->tag($node, $indent, $tree),
            'group' => $this->each($node->children, $indent, $tree),
            'view' => $this->include($node, $indent, $tree),
            'component' => $this->component($node, $indent, $tree),
            'region' => $this->region($node, $indent, $tree),
            'slot' => $this->slot($node, $indent, $tree),
            'stack' => [$indent."@stack('".$this->quote($node->value)."')"],
            'directive' => $this->directive($node, $indent, $tree),
            'html' => [$indent.$this->escape($node->value)],
            default => [],
        };
    }

    /**
     * @param  list<Node>  $nodes
     * @return list<string>
     */
    private function each(array $nodes, string $indent, Tree $tree): array
    {
        $lines = [];

        foreach ($nodes as $node) {
            array_push($lines, ...$this->node($node, $indent, $tree));
        }

        return $lines;
    }

    /** @return list<string> */
    private function tag(Node $node, string $indent, Tree $tree): array
    {
        $root = $node->parent === null && $node->value === 'html';
        $attrs = $this->attributes($node->attrs, false);

        // A named slot (`<x-slot:brand>`) is a component's: anywhere else Blade fails on the page.
        if (str_starts_with($node->value, 'x-slot:') && $node->parent?->kind !== 'component') {
            $tree->note($node->origin, "tag {$node->id}", "{$node->value} is a slot of a component and stands only in one: left out");

            return [];
        }

        if ($root) {
            // `lang` is the page's, never a patch's (§3.1).
            $attrs = ' lang="{{ str_replace(\'_\', \'-\', app()->getLocale()) }}"'.$attrs;
        }

        $open = "<{$node->value}{$attrs}>";

        if (in_array(strtolower($node->value), self::VOID, true)) {
            return [$indent.$open];
        }

        $children = $this->each($node->children, $root ? $indent : $indent.self::INDENT, $tree);

        if ($children === []) {
            return [...($root ? ['<!doctype html>'] : []), $indent.$open."</{$node->value}>"];
        }

        return [...($root ? [$indent.'<!doctype html>'] : []), $indent.$open, ...$children, $indent."</{$node->value}>"];
    }

    /** @return list<string> */
    private function include(Node $node, string $indent, Tree $tree): array
    {
        if (! $this->probe->view($node->value)) {
            $tree->note($node->origin, "view {$node->id}", "no view \"{$node->value}\": left out");

            return [];
        }

        $with = $node->with === [] ? '' : ', '.$this->php($node->with);

        return [$indent."@include('".$this->quote($node->value)."'{$with})"];
    }

    /** @return list<string> */
    private function component(Node $node, string $indent, Tree $tree): array
    {
        if (! $this->probe->component($node->value)) {
            $tree->note($node->origin, "component {$node->id}", "no component \"{$node->value}\": left out");

            return [];
        }

        $open = "<x-{$node->value}".$this->attributes($node->attrs, true).$this->props($node->props);
        $children = $this->each($node->children, $indent.self::INDENT, $tree);

        if ($children === []) {
            return [$indent.$open.' />'];
        }

        // One leaf inside stays on the line: `<x-webx-notice-bar>@stack('notice')</x-webx-notice-bar>`.
        if (count($children) === 1 && count($node->children) === 1 && ! $node->children[0]->isContainer()) {
            return [$indent.$open.'>'.ltrim($children[0])."</x-{$node->value}>"];
        }

        return [$indent.$open.'>', ...$children, $indent."</x-{$node->value}>"];
    }

    /**
     * A zone of blocks the editor fills (§2.3). Without module-blocks there is no region to print,
     * and the fallback view stands in its place, decided now rather than on every request.
     *
     * @return list<string>
     */
    private function region(Node $node, string $indent, Tree $tree): array
    {
        $fallback = $node->regionFallback;

        if ($this->probe->component('webx-blocks::region')) {
            $attr = $fallback === null ? '' : ' fallback="'.$this->attribute($fallback).'"';

            return [$indent.'<x-webx-blocks::region name="'.$this->attribute($node->value).'"'.$attr.' />'];
        }

        if ($fallback !== null && $this->probe->view($fallback)) {
            return [$indent."@include('".$this->quote($fallback)."')"];
        }

        return [];
    }

    /**
     * The caller's slot (§2.4): the default one as it is; a named one while it is handed and not
     * empty, else its fallback — a module's view puts `@webxSeo` there already, and a second one
     * would be a second <title>.
     *
     * @return list<string>
     */
    private function slot(Node $node, string $indent, Tree $tree): array
    {
        if ($node->value === 'default') {
            return [$indent.'{{ $slot }}'];
        }

        $variable = '$'.$this->variable($node->value);
        $fallback = $this->each($node->fallback, $indent.self::INDENT, $tree);

        if ($fallback === []) {
            return [$indent."{{ {$variable} ?? '' }}"];
        }

        return [
            $indent."@if (isset({$variable}) && trim((string) {$variable}) !== '')",
            $indent.self::INDENT."{{ {$variable} }}",
            $indent.'@else',
            ...$fallback,
            $indent.'@endif',
        ];
    }

    /** @return list<string> */
    private function directive(Node $node, string $indent, Tree $tree): array
    {
        if (! $this->probe->directive($node->value)) {
            $tree->note($node->origin, "directive {$node->id}", "no directive @{$node->value}: left out");

            return [];
        }

        return [$indent.'@'.$node->value.($node->args === null ? '' : '('.$node->args.')')];
    }

    /**
     * Attributes as they are written (§3.1): `true` bare, a string escaped, `trans::` translated
     * on the request — in a component tag as a bound attribute, since that is PHP there.
     *
     * @param  array<string, string|bool>  $attrs
     */
    private function attributes(array $attrs, bool $component): string
    {
        $html = '';

        foreach ($attrs as $name => $value) {
            if ($value === true) {
                $html .= " {$name}";
            } elseif (is_string($value) && str_starts_with($value, 'trans::')) {
                $key = $this->quote(substr($value, 7));
                $html .= $component ? " :{$name}=\"__('{$key}')\"" : " {$name}=\"{{ __('{$key}') }}\"";
            } elseif (is_string($value)) {
                $html .= " {$name}=\"".$this->attribute($value).'"';
            }
        }

        return $html;
    }

    /** @param array<string, mixed> $props */
    private function props(array $props): string
    {
        $html = '';

        foreach ($props as $name => $value) {
            if (is_string($value) && str_starts_with($value, 'trans::')) {
                $html .= " :{$name}=\"__('".$this->quote(substr($value, 7))."')\"";
            } elseif (is_string($value)) {
                $html .= " {$name}=\"".$this->attribute($value).'"';
            } else {
                $html .= " :{$name}=\"".htmlspecialchars($this->php($value), ENT_QUOTES).'"';
            }
        }

        return $html;
    }

    /** A literal as PHP on one line: `5`, `true`, `['a' => 1]`. */
    private function php(mixed $value): string
    {
        if (is_array($value)) {
            $items = [];

            foreach ($value as $key => $item) {
                $items[] = (array_is_list($value) ? '' : var_export($key, true).' => ').$this->php($item);
            }

            return '['.implode(', ', $items).']';
        }

        return $value === null ? 'null' : var_export($value, true);
    }

    private function attribute(string $value): string
    {
        return $this->escape(htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8', false));
    }

    /** Blade in a literal is text, not code: `@if` stays `@if` on the page, `{{` stays `{{`. */
    private function escape(string $text): string
    {
        $text = (string) preg_replace('/@(?=\w)/', '@@', $text);

        return str_replace(['{{', '{!!'], ['@{{', '@{!!'], $text);
    }

    private function quote(string $value): string
    {
        return str_replace(['\\', "'"], ['\\\\', "\\'"], $value);
    }

    private function variable(string $slot): string
    {
        return lcfirst(str_replace(['-', '_', '.'], '', ucwords($slot, '-_.')));
    }
}
