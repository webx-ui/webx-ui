// The styles of a few components, for the panel's pages that stand outside the Vue app — the
// consent screen an agent sends a person to, the gate of a closed site. Those are Blade: they
// cannot mount `WxButton`, and a button drawn again by hand drifts from the panel's (it did: a
// size taller, a size larger). So the rules are taken from the components themselves, as they
// are written, and module-admin carries the result next to its copy of the tokens. Such a page
// writes the same classes the component renders: `wx-button wx-button--primary wx-button--solid
// wx-button--md`.
//
// `node scripts/server-styles.mjs` writes the copy (the build runs it); src/serverStyles.test.ts
// fails when the components changed and the copy did not. A checkout without the php half skips.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The components a server page draws, in the order their rules are written out. */
export const SERVER_COMPONENTS = ['Card', 'Alert', 'Checkbox', 'Button', 'Link']

export const serverStylesPath = resolve(
  root,
  '../../php/packages/module-admin/resources/css/components.css',
)

/** The scoped block of a component, with `:deep(x)` unwrapped — outside Vue there is no scope. */
function stylesOf(name) {
  const source = readFileSync(resolve(root, `src/components/${name}/${name}.vue`), 'utf8')
  const found = source.match(/<style scoped>([\s\S]*?)<\/style>/)

  if (!found) throw new Error(`${name}.vue has no scoped style block`)

  return found[1].replace(/:deep\(([^)]*)\)/g, '$1').trim()
}

export function serverStyles() {
  const parts = SERVER_COMPONENTS.map((name) => `/* Wx${name} */\n${stylesOf(name)}\n`)

  return `/* Generated by packages/core/scripts/server-styles.mjs from the components of @webx-ui/core. Do not edit. */\n\n${parts.join('\n')}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = dirname(serverStylesPath)

  if (existsSync(resolve(target, '..'))) {
    mkdirSync(target, { recursive: true })
    writeFileSync(serverStylesPath, serverStyles())
    console.log(`server styles: ${SERVER_COMPONENTS.join(', ')} -> ${serverStylesPath}`)
  }
}
